//! farm-host 构建脚本（ticket #11）：把 Dioxus 面板编译成 wasm，交给 rust-embed 嵌入。
//!
//! ADR-0003 决策 4（单二进制）：面板产物必须随宿主二进制一起走，所以这里在编译
//! `farm-host` 之前把 `farm-panel` 编成 `wasm32-unknown-unknown`、过一遍
//! `wasm-bindgen --target web`，生成 `index.html`，然后把目录经
//! `PANEL_DIST` 交给 `src/panel.rs` 的 `RustEmbed` 派生。
//!
//! 三条硬规则：
//!
//! 1. **绝不因面板失败而让宿主编译不过。** 拿不到 wasm 产物时回退到
//!    `panel/placeholder.html`（纯静态占位页），宿主照常编译、照常伺服 `/`，
//!    并发 `cargo:warning` 说明退化原因。
//! 2. **防 build.rs 递归。** 内层 cargo 子进程带 `FARM_PANEL_BUILDING=1` 哨兵；
//!    若 build.rs 发现自己是内层调用，直接走回退，不再调 cargo。
//! 3. **内层 cargo 用独立的 target 目录**（`<target>/farm-panel-wasm`）。
//!    宿主构建期间 cargo 对 `target/<profile>/.cargo-lock` 持独占锁，内层再用
//!    同一个 profile 目录会死锁（父等子、子等锁）；目录分开即无锁竞争，
//!    也不污染宿主自己的产物，且仍留在 gitignore 的 `/target` 里。

use std::path::{Path, PathBuf};
use std::process::Command;

/// 面板 crate 名（workspace 成员，ADR-0003 五分法）。
const PANEL_CRATE: &str = "farm-panel";
/// 面板 wasm 目标三元组。
const WASM_TARGET: &str = "wasm32-unknown-unknown";
/// 内层 cargo 专用 target 目录名（与宿主自己的 target 目录平级，避免拿锁死锁）。
const PANEL_TARGET_DIR_NAME: &str = "farm-panel-wasm";
/// 防递归哨兵：内层 cargo 子进程带上它。
const RECURSION_SENTINEL: &str = "FARM_PANEL_BUILDING";
/// 面板 wasm 产物就绪时使用的页面模板（`{{PANEL_JS}}` 由本脚本替换）。
const INDEX_TEMPLATE: &str = "panel/index.html";
/// 面板产物拿不到时的回退页（`{{CONTRACT_VERSION}}` 由本脚本替换）。
const PLACEHOLDER_TEMPLATE: &str = "panel/placeholder.html";
/// 回退页里契约版本解析失败时的占位说明。
const UNKNOWN_CONTRACT_VERSION: &str = "未知";

fn main() {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("build scripts get OUT_DIR"));
    let dist = out_dir.join("panel-dist");

    rerun_declarations();

    // 每次都重建嵌入目录：rust-embed 在编译期读它，陈旧文件会被嵌进去。
    let _ = std::fs::remove_dir_all(&dist);
    std::fs::create_dir_all(&dist)
        .unwrap_or_else(|e| panic!("create panel dist {}: {e}", dist.display()));

    let js_glue = build_panel(&manifest_dir, &dist);

    let html = match &js_glue {
        Some(js) => render_template(
            &manifest_dir.join(INDEX_TEMPLATE),
            &[("PANEL_JS", js.as_str())],
        ),
        None => {
            println!(
                "cargo:warning=farm-host: panel wasm unavailable; embedding the static placeholder page at / (see farm-host/build.rs)"
            );
            let version = contract_version(&manifest_dir);
            render_template(
                &manifest_dir.join(PLACEHOLDER_TEMPLATE),
                &[("CONTRACT_VERSION", &version)],
            )
        }
    };
    std::fs::write(dist.join("index.html"), html).expect("write panel index.html");

    // rust-embed 的 `#[folder]` 只接受字面量，所以把绝对路径写进生成文件。
    let generated = format!(
        "/// GENERATED by farm-host/build.rs — do not edit.\n\
         #[derive(rust_embed::RustEmbed)]\n\
         #[folder = {folder:?}]\n\
         pub struct PanelAssets;\n",
        folder = dist.display().to_string()
    );
    std::fs::write(out_dir.join("panel_assets.rs"), generated).expect("write panel_assets.rs");

    println!("cargo:rustc-env=PANEL_DIST={}", dist.display());
}

fn rerun_declarations() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={INDEX_TEMPLATE}");
    println!("cargo:rerun-if-changed={PLACEHOLDER_TEMPLATE}");
    println!("cargo:rerun-if-changed=../farm-panel/src/lib.rs");
    println!("cargo:rerun-if-changed=../farm-panel/Cargo.toml");
    for key in [
        "FARM_PANEL_DIST",
        "FARM_PANEL_RELEASE",
        "FARM_SKIP_PANEL_BUILD",
        RECURSION_SENTINEL,
    ] {
        println!("cargo:rerun-if-env-changed={key}");
    }
}

/// 构建面板 wasm 并跑 wasm-bindgen，成功返回 JS 胶水文件名（占位回退返回 `None`）。
fn build_panel(manifest_dir: &Path, dist: &Path) -> Option<String> {
    // 规则 2：防递归。
    if std::env::var_os(RECURSION_SENTINEL).is_some() {
        println!(
            "cargo:warning=farm-host: skipping the panel build ({RECURSION_SENTINEL} is set)"
        );
        return None;
    }

    // 逃生舱：调用方给一个已构建好的 dist，直接搬进来。
    if let Some(prebuilt) = std::env::var_os("FARM_PANEL_DIST") {
        let prebuilt = PathBuf::from(prebuilt);
        match copy_tree(&prebuilt, dist) {
            Ok(()) => {
                println!(
                    "cargo:warning=farm-host: using the prebuilt panel dist {}",
                    prebuilt.display()
                );
                return js_glue_name(dist);
            }
            Err(e) => println!(
                "cargo:warning=farm-host: FARM_PANEL_DIST={} is unusable ({e}); building the panel",
                prebuilt.display()
            ),
        }
    }

    if std::env::var_os("FARM_SKIP_PANEL_BUILD").is_some() {
        println!(
            "cargo:warning=farm-host: FARM_SKIP_PANEL_BUILD is set; embedding the placeholder page"
        );
        return None;
    }

    let workspace_root = workspace_root(manifest_dir);
    let target_dir = panel_target_dir(&workspace_root);
    let release = std::env::var("PROFILE").as_deref() == Ok("release")
        || std::env::var_os("FARM_PANEL_RELEASE").is_some();

    let mut cmd = Command::new(cargo_bin());
    cmd.current_dir(&workspace_root)
        .env(RECURSION_SENTINEL, "1")
        .args(["build", "-p", PANEL_CRATE, "--target", WASM_TARGET])
        .arg("--target-dir")
        .arg(&target_dir);
    if release {
        cmd.arg("--release");
    }
    let output = match cmd.output() {
        Ok(output) => output,
        Err(e) => {
            println!("cargo:warning=farm-host: cannot spawn the inner cargo ({e}); embedding the placeholder page");
            return None;
        }
    };
    if !output.status.success() {
        let tail = tail(&String::from_utf8_lossy(&output.stderr), 12);
        println!(
            "cargo:warning=farm-host: `cargo build -p {PANEL_CRATE} --target {WASM_TARGET}` failed; embedding the placeholder page\n{tail}"
        );
        return None;
    }

    let wasm = match wasm_artifact(&target_dir, release) {
        Some(wasm) => wasm,
        None => {
            println!("cargo:warning=farm-host: panel wasm artifact not found under {}; embedding the placeholder page", target_dir.display());
            return None;
        }
    };

    let bindgen = Command::new("wasm-bindgen")
        .args(["--target", "web", "--out-dir"])
        .arg(dist)
        .arg(&wasm)
        .output();
    match bindgen {
        Ok(out) if out.status.success() => {}
        Ok(out) => {
            let tail = tail(&String::from_utf8_lossy(&out.stderr), 12);
            println!(
                "cargo:warning=farm-host: `wasm-bindgen --target web` failed; embedding the placeholder page\n{tail}"
            );
            return None;
        }
        Err(e) => {
            println!("cargo:warning=farm-host: the wasm-bindgen CLI is unavailable ({e}); embedding the placeholder page");
            return None;
        }
    }

    js_glue_name(dist)
}

/// 内层 cargo 可执行文件（cargo 给 build script 设了 `CARGO`）。
fn cargo_bin() -> String {
    std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_string())
}

/// workspace 根：`farm-host` 是根 workspace 的成员，根 manifest 在父目录。
fn workspace_root(manifest_dir: &Path) -> PathBuf {
    let parent = manifest_dir.join("..");
    let manifest = parent.join("Cargo.toml");
    if manifest.exists() {
        if let Ok(text) = std::fs::read_to_string(&manifest) {
            if text.contains("[workspace]") {
                return normalize(&parent);
            }
        }
    }
    manifest_dir.to_path_buf()
}

/// 内层 cargo 的 target 目录：宿主 target 目录下的独立子目录（锁不冲突）。
fn panel_target_dir(workspace_root: &Path) -> PathBuf {
    let base = std::env::var_os("CARGO_TARGET_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| workspace_root.join("target"));
    normalize(&base).join(PANEL_TARGET_DIR_NAME)
}

/// 面板 wasm 产物路径（`<target>/wasm32-unknown-unknown/{debug,release}/farm_panel.wasm`）。
fn wasm_artifact(target_dir: &Path, release: bool) -> Option<PathBuf> {
    let profile = if release { "release" } else { "debug" };
    let direct = target_dir
        .join(WASM_TARGET)
        .join(profile)
        .join("farm_panel.wasm");
    if direct.exists() {
        return Some(direct);
    }
    // profile 目录名在不同 cargo 版本/设置下可能不同：兜底扫一层。
    let dir = target_dir.join(WASM_TARGET);
    let entries = std::fs::read_dir(&dir).ok()?;
    for entry in entries.flatten() {
        let candidate = entry.path().join("farm_panel.wasm");
        if candidate.exists() {
            return Some(candidate);
        }
    }
    None
}

/// dist 顶层唯一的 `.js` 胶水文件（wasm-bindgen 的产物名与 crate 名一致）。
fn js_glue_name(dist: &Path) -> Option<String> {
    let entries = std::fs::read_dir(dist).ok()?;
    let mut names: Vec<String> = entries
        .flatten()
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().to_string();
            if name.ends_with(".js") {
                Some(name)
            } else {
                None
            }
        })
        .collect();
    names.sort();
    match names.len() {
        1 => Some(names.remove(0)),
        0 => {
            println!(
                "cargo:warning=farm-host: no JS glue in the panel dist; embedding the placeholder page"
            );
            None
        }
        _ => {
            println!("cargo:warning=farm-host: ambiguous JS glue in the panel dist ({names:?}); embedding the placeholder page");
            None
        }
    }
}

/// 读模板并替换 `{{KEY}}` 占位符。
fn render_template(path: &Path, subs: &[(&str, &str)]) -> String {
    let template = std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("read panel template {}: {e}", path.display()));
    let mut out = template;
    for (key, value) in subs {
        out = out.replace(&format!("{{{{{key}}}}}"), value);
    }
    out
}

/// 从 `farm-sdk/src/handshake.rs` 取契约版本（单一源；仅供回退页展示）。
fn contract_version(manifest_dir: &Path) -> String {
    let path = manifest_dir.join("../farm-sdk/src/handshake.rs");
    let Ok(text) = std::fs::read_to_string(&path) else {
        return UNKNOWN_CONTRACT_VERSION.to_string();
    };
    for line in text.lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("pub const CONTRACT_VERSION: &str = ") {
            if let Some(version) = rest.trim().strip_prefix('"').and_then(|v| v.strip_suffix('"'))
            {
                return version.to_string();
            }
        }
    }
    UNKNOWN_CONTRACT_VERSION.to_string()
}

/// 递归拷贝目录（保留相对结构：wasm-bindgen 的 JS 会 `import './snippets/...'`）。
fn copy_tree(from: &Path, to: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(to)?;
    for entry in std::fs::read_dir(from)? {
        let entry = entry?;
        let target = to.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            copy_tree(&entry.path(), &target)?;
        } else {
            std::fs::copy(entry.path(), &target)?;
        }
    }
    Ok(())
}

/// 取文本末尾若干行（塞进 `cargo:warning` 便于诊断）。
fn tail(text: &str, lines: usize) -> String {
    let collected: Vec<&str> = text.lines().rev().take(lines).collect();
    collected.into_iter().rev().collect::<Vec<_>>().join("\n")
}

/// 去掉 `.` 组件（构建期路径规整，避免 `./` 干扰展示）。
fn normalize(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for component in path.components() {
        match component {
            std::path::Component::CurDir => {}
            other => out.push(other.as_os_str()),
        }
    }
    out
}
